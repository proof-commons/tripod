//! The transaction-wide confidential materializer, driven by the real
//! arithmetic on both sides.
//!
//! # Why this file exists beside the construction package's own tests
//!
//! The construction package cannot reach either origin: it declares two
//! traits and depends on neither implementation, so its own tests drive
//! stand-ins and measure control flow. That is the right measurement
//! there and it is not evidence about cryptography.
//!
//! Here both origins are real. The commitments are the first-party bignum
//! oracle's and the reference bindings', independently computed and
//! compared through a function that takes one of each type; the range
//! proofs are generated by the bindings the target vendors and VERIFIED
//! by the same bindings' verifier against the commitment, the unblinded
//! asset generator, and the output program. So what this file establishes
//! is that the seven stages produce a candidate whose proofs are real
//! proofs about the real commitments.
//!
//! # What it does not establish
//!
//! No target has seen any of this. Whether a chain accepts the candidate
//! is a target question, this file asks no target anything, and nothing
//! here is a verdict about one. The proof generation and verification are
//! both conformance-to-the-target's-own-implementation evidence and are
//! not independent evidence; the independent claim belongs to the
//! commitment arithmetic alone.
//!
//! # Public test material
//!
//! Every fixture, scalar, program, and asset below is disposable public
//! test material. Nothing is a secret and nothing authorizes anything.

