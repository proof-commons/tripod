/// The published disposable protocol asset, in commit order.
const ASSET: [u8; 32] = [0x3b; 32];

/// The predecessor case's public handle.
const PREDECESSOR: &str = "ctf-v1/wave-three-live-predecessor";

/// The successor case's public handle.
const SUCCESSOR: &str = "ctf-v1/wave-three-live-successor";

/// The predecessor output the candidate consumes.
const CONSUMED_OUTPUT: usize = 0;

/// The predecessor's two semantic amounts.
const PREDECESSOR_AMOUNTS: [u64; 2] = [700_000_000, 300_000_000];

/// The successor's two semantic amounts, summing to the consumed one.
const SUCCESSOR_AMOUNTS: [u64; 2] = [400_000_000, 300_000_000];

/// The predecessor's two output programs, deliberately distinct.
fn predecessor_programs() -> [Vec<u8>; 2] {
    [vec![0x51], vec![0x51, 0x75, 0x51]]
}

/// The successor's two output programs, also distinct, so that a proof
/// built for one cannot verify against the other.
fn successor_programs() -> [Vec<u8>; 2] {
    [vec![0x52, 0x20, 0xaa], vec![0x52, 0x20, 0xbb]]
}

/// The profiles both registered cases select.
const fn funding_profiles() -> ConfidentialFundingProfiles {
    ConfidentialFundingProfiles {
        representation: FundingRepresentationProfile::ExplicitAssetConfidentialValue,
        custody: FundingCustodyProfile::CentralPublicFixtures,
        materializer: FundingMaterializerProfile::GuideCtfDeterministicV1,
        reproducibility_contract: ReproducibilityContract::ByteIdentity,
    }
}

/// The profiles the materialization runs under.
const fn materialization_profiles() -> ConfidentialMaterializationProfiles {
    ConfidentialMaterializationProfiles {
        reproducibility_contract: ReproducibilityContract::ByteIdentity,
        custody_profile: ConfidentialCustodyProfile::CentralPublicFixtures,
        materializer_profile: ConfidentialMaterializerProfile::GuideCtfDeterministicV1,
        proof_profile: ConfidentialProofProfile::ExplicitAssetRangeproofV1,
        nonce_profile: ConfidentialNonceProfile::DeterministicDerivedV1,
        order_profile: ConfidentialOrderProfile::FixtureFixedOrder,
        retry_profile: ConfidentialRetryProfile::NoRetry,
    }
}

/// One manifest, built from its own parts.
fn manifest(
    handle: &str,
    input_blinder_sum: [u8; 32],
    amounts: [u64; 2],
    programs: [Vec<u8>; 2],
) -> ConfidentialFixtureManifest {
    let [first, second] = programs;
    ConfidentialFixtureManifest {
        handle: ConfidentialFixtureHandle::new(handle.to_owned()),
        material_class: PublicDisposableTestMaterial::EXPECTED,
        derivation_profile: FixtureDerivationProfile::GuideCtfV1,
        profiles: funding_profiles(),
        retry_limit: MAX_PARITY_COUNTER,
        explicit_asset: ASSET,
        input_blinder_sum,
        outputs: vec![
            ConfidentialFixtureOutput {
                role: FixtureOutputRole::Primary,
                semantic_amount: amounts[0],
                output_program: first,
            },
            ConfidentialFixtureOutput {
                role: FixtureOutputRole::Balancing,
                semantic_amount: amounts[1],
                output_program: second,
            },
        ],
    }
}

/// The predecessor registry, frozen.
///
/// Registered alone so that its derived openings can be read before the
/// successor's manifest is written: the successor's input blinder sum is
/// the consumed output's own value blinder, which is a derived value and
/// not one a test may choose.
fn frozen_predecessor() -> FrozenConfidentialFixtureRegistry {
    let mut registry = ConfidentialFixtureRegistry::new();
    registry
        .register(manifest(
            PREDECESSOR,
            [0_u8; 32],
            PREDECESSOR_AMOUNTS,
            predecessor_programs(),
        ))
        .expect("the predecessor manifest registers");
    registry.freeze()
}

/// The derived openings of one resolved fixture.
fn openings(
    fixture: &ResolvedFixture,
) -> &[target_elements_conformance::confidential_fixture::DerivedOpening] {
    match fixture.openings() {
        FixtureOpenings::Derived { openings, .. } => openings,
        FixtureOpenings::RunProduced => panic!("the byte-identity contract derives its openings"),
    }
}

/// One projected fixture, from a resolved one.
fn project(fixture: &ResolvedFixture) -> ConfidentialFixtureView {
    let derived = openings(fixture);
    let outputs = fixture
        .outputs()
        .iter()
        .zip(derived)
        .map(|(output, opening)| {
            ConfidentialFixtureOutputView::new(
                match output.role {
                    FixtureOutputRole::Primary => ConfidentialOutputRole::Primary,
                    FixtureOutputRole::Balancing => ConfidentialOutputRole::Balancing,
                    // The registry's role vocabulary is open and the
                    // view's is not. A role added there without a place
                    // here stops this test compiling, which is where a
                    // reader wants to find out.
                    other => panic!("the view projects no role named {other:?}"),
                },
                output.semantic_amount,
                output.output_program.clone(),
                opening.value_blinder,
                opening.nonce_input,
                opening.rangeproof_seed,
            )
        })
        .collect();
    ConfidentialFixtureView::new(
        *fixture.digest().bytes(),
        AssetId::from_internal(*fixture.explicit_asset()),
        *fixture.input_blinder_sum(),
        ParityOutcome::Settled {
            counter: match fixture.openings() {
                FixtureOpenings::Derived { parity_counter, .. } => *parity_counter,
                FixtureOpenings::RunProduced => 0,
            },
        },
        outputs,
    )
}

/// Everything one materialization needs, built from two real registries.
struct Ceremony {
    view: FrozenConfidentialFixtureView,
    intent: ConfidentialConstructionIntent,
}

/// The predecessor and successor cases, registered, frozen, and projected.
fn ceremony() -> Ceremony {
    let predecessor_registry = frozen_predecessor();
    let predecessor_handle = ConfidentialFixtureHandle::new(PREDECESSOR.to_owned());
    let predecessor_digest = *predecessor_registry
        .registered_digest(&predecessor_handle)
        .expect("the predecessor registered");
    let predecessor = predecessor_registry
        .resolve(&predecessor_handle, &predecessor_digest)
        .expect("the predecessor resolves under its own digest");
    let consumed_opening = openings(predecessor)[CONSUMED_OUTPUT].clone();

    // The successor balances against the consumed output's own blinder,
    // which is derived rather than chosen: a test that picked a round
    // number here would be testing a case the ceremony cannot produce.
    let mut successor_registry = ConfidentialFixtureRegistry::new();
    successor_registry
        .register(manifest(
            SUCCESSOR,
            consumed_opening.value_blinder,
            SUCCESSOR_AMOUNTS,
            successor_programs(),
        ))
        .expect("the successor manifest registers");
    let successor_registry = successor_registry.freeze();
    let successor_handle = ConfidentialFixtureHandle::new(SUCCESSOR.to_owned());
    let successor_digest = *successor_registry
        .registered_digest(&successor_handle)
        .expect("the successor registered");
    let successor = successor_registry
        .resolve(&successor_handle, &successor_digest)
        .expect("the successor resolves under its own digest");

    let mut entries = BTreeMap::new();
    entries.insert(PREDECESSOR.to_owned(), project(predecessor));
    entries.insert(SUCCESSOR.to_owned(), project(successor));

    let outpoint = Outpoint::new(Txid::from_internal([0xc1; 32]), 0).expect("a fixture outpoint");
    let input = ConfidentialInputIntent::new(
        outpoint,
        AssetField::Explicit(AssetId::from_internal(ASSET)),
        // The value field a target would have been observed to hold: the
        // predecessor's own derived commitment, which the preflight
        // recomputes rather than trusting.
        ValueField::Commitment(consumed_opening.value_commitment),
        predecessor_programs()[CONSUMED_OUTPUT].clone(),
        0xffff_ffff,
        FixtureOpeningReference::new(
            PREDECESSOR.to_owned(),
            *predecessor_digest.bytes(),
            CONSUMED_OUTPUT,
        ),
        PREDECESSOR_AMOUNTS[CONSUMED_OUTPUT],
        [0_u8; SCALAR_BYTES],
    );

    let programs = successor_programs();
    let destinations = vec![
        ConfidentialDestinationIntent::new(
            SUCCESSOR_AMOUNTS[0],
            AssetId::from_internal(ASSET),
            programs[0].clone(),
            FixtureOpeningReference::new(SUCCESSOR.to_owned(), *successor_digest.bytes(), 0),
            ConfidentialOutputRole::Primary,
        ),
        ConfidentialDestinationIntent::new(
            SUCCESSOR_AMOUNTS[1],
            AssetId::from_internal(ASSET),
            programs[1].clone(),
            FixtureOpeningReference::new(SUCCESSOR.to_owned(), *successor_digest.bytes(), 1),
            ConfidentialOutputRole::Balancing,
        ),
    ];

    Ceremony {
        view: FrozenConfidentialFixtureView::new(entries),
        intent: ConfidentialConstructionIntent::new(
            vec![input],
            destinations,
            NonProtocolFundingRegion::default(),
            materialization_profiles(),
            3,
            0,
        ),
    }
}

/// The asset as the target prints it, which is the reverse of the order
/// it commits to it in.
fn printed_asset() -> String {
    use std::fmt::Write as _;

    let mut printed = String::with_capacity(ASSET.len() * 2);
    for byte in ASSET.iter().rev() {
        write!(printed, "{byte:02x}").expect("writing to a string does not fail");
    }
    printed
}

/// One materialization with both real origins wired in.
#[test]
fn the_real_origins_materialize_one_proof_bearing_candidate() {
    let ceremony = ceremony();
    let candidate = materialize_confidential_candidate(
        &ceremony.intent,
        &ceremony.view,
        &ReferenceConfidentialMaterializer::new(),
        &FirstPartyCommitmentCheck::new(),
    )
    .expect("the two origins agree and the candidate materializes");

    let protected = candidate.proof_finalized().protected();
    assert_eq!(protected.outputs().len(), 2, "two protocol outputs");
    assert_eq!(
        protected.output_witnesses().len(),
        2,
        "one output-witness entry per output",
    );

    // The bytes round-trip, which is this wave's exit condition and is
    // checked here on a candidate whose proofs are real.
    let bytes = protected.encode();
    let decoded = transaction::bytes::TargetTransaction::decode(&bytes)
        .expect("a real proof-bearing candidate decodes");
    assert_eq!(decoded.encode(), bytes, "and re-encodes to itself");
    assert_eq!(&decoded, protected, "and to the same typed value");

    // Every proof is a real proof about the real commitment, verified by
    // the reference verifier against the three things it must bind.
    let verifier = ReferenceRangeproofVerifier::new();
    for (index, output) in protected.outputs().iter().enumerate() {
        let commitment = match output.value() {
            ValueField::Commitment(commitment) => commitment,
            other => panic!("the protocol outputs are confidential, not {other:?}"),
        };
        let witness = &protected.output_witnesses()[index];
        assert!(
            !witness.range_proof().is_empty(),
            "a confidential value carries a nonempty proof",
        );
        assert!(
            witness.surjection_proof().is_empty(),
            "and an empty surjection field",
        );
        assert!(
            verifier.verifies(
                witness.range_proof(),
                &commitment,
                &printed_asset(),
                output.program(),
            ),
            "and the proof verifies against this output's own commitment, generator, and program",
        );
    }
}

/// A proof does not verify against another output's program.
///
/// The binding, measured rather than assumed. The proofs are the
/// candidate's own and the programs are swapped between them, so what
/// changed is which output each proof is checked against and nothing
/// else.
#[test]
fn a_proof_does_not_verify_against_another_outputs_program() {
    let ceremony = ceremony();
    let candidate = materialize_confidential_candidate(
        &ceremony.intent,
        &ceremony.view,
        &ReferenceConfidentialMaterializer::new(),
        &FirstPartyCommitmentCheck::new(),
    )
    .expect("the candidate materializes");
    let protected = candidate.proof_finalized().protected();
    let verifier = ReferenceRangeproofVerifier::new();

    let first_commitment = match protected.outputs()[0].value() {
        ValueField::Commitment(commitment) => commitment,
        other => panic!("the protocol outputs are confidential, not {other:?}"),
    };

    assert!(
        !verifier.verifies(
            protected.output_witnesses()[0].range_proof(),
            &first_commitment,
            &printed_asset(),
            protected.outputs()[1].program(),
        ),
        "a proof built for one program does not verify against another",
    );
}

/// The reference bindings may not be the independent check.
///
/// The rule with real implementations behind it rather than stand-ins:
/// wiring the same library in on both sides is refused at the boundary
/// that assembles the comparison, and the refusal names the output.
#[test]
fn the_reference_bindings_may_not_check_their_own_construction() {
    /// The reference materializer's arithmetic, offered as an
    /// independent check.
    #[derive(Debug, Default)]
    struct ReferenceAsCheck(ReferenceConfidentialMaterializer);

    impl IndependentCommitmentCheck for ReferenceAsCheck {
        fn origin(&self) -> CommitmentOrigin {
            CommitmentOrigin::ReferenceImplementation
        }

        fn recompute(
            &self,
            explicit_asset: AssetId,
            semantic_amount: u64,
            value_blinder: &[u8; SCALAR_BYTES],
        ) -> Option<IndependentCommitment> {
            use transaction::live_materialize::ConfidentialProofMaterializer;
            let materialized =
                self.0
                    .value_commitment(explicit_asset, semantic_amount, value_blinder)?;
            Some(IndependentCommitment::from_independent_recomputation(
                *materialized.bytes(),
            ))
        }

        fn solve_balancing_blinder(
            &self,
            input_blinder_sum: &[u8; SCALAR_BYTES],
            other_blinders: &[[u8; SCALAR_BYTES]],
        ) -> Option<[u8; SCALAR_BYTES]> {
            FirstPartyCommitmentCheck::new()
                .solve_balancing_blinder(input_blinder_sum, other_blinders)
        }
    }

    let ceremony = ceremony();
    let refusal = materialize_confidential_candidate(
        &ceremony.intent,
        &ceremony.view,
        &ReferenceConfidentialMaterializer::new(),
        &ReferenceAsCheck::default(),
    )
    .expect_err("one library may not be both the construction and the check on it");

    assert_eq!(
        refusal,
        MaterializationRefusal::IndependentCommitmentOriginNotDistinct { output: 0 },
    );
}

/// The two real origins agree on every commitment.
///
/// The agreement is what the successful materialization above already
/// rests on, and it is worth stating separately: the first-party bignum
/// arithmetic and the reference bindings, computing the same commitment
/// from the same published opening, produce the same thirty-three bytes.
/// A disagreement would be a finding about one of them rather than about
/// the candidate.
#[test]
fn the_first_party_oracle_and_the_reference_bindings_agree() {
    use transaction::live_materialize::{ConfidentialProofMaterializer, commitments_agree};

    let predecessor_registry = frozen_predecessor();
    let handle = ConfidentialFixtureHandle::new(PREDECESSOR.to_owned());
    let digest = *predecessor_registry
        .registered_digest(&handle)
        .expect("the predecessor registered");
    let predecessor = predecessor_registry
        .resolve(&handle, &digest)
        .expect("the predecessor resolves");

    let reference = ReferenceConfidentialMaterializer::new();
    let first_party = FirstPartyCommitmentCheck::new();
    let asset = AssetId::from_internal(ASSET);

    for (output, opening) in predecessor.outputs().iter().zip(openings(predecessor)) {
        let materialized = reference
            .value_commitment(asset, output.semantic_amount, &opening.value_blinder)
            .expect("the reference bindings commit");
        let recomputed = first_party
            .recompute(asset, output.semantic_amount, &opening.value_blinder)
            .expect("the first-party oracle commits");

        assert!(
            commitments_agree(&materialized, &recomputed),
            "two origins, one answer",
        );
        assert_eq!(
            materialized.bytes(),
            &opening.value_commitment,
            "and it is the commitment the registry derived",
        );
    }
}
